// Creates secrets/testnet-keys.json with fresh throwaway keys. Prints addresses only, never a private key.
// Usage: node app/src/keys.js            testnet keys (local, Sepolia)
//        node app/src/keys.js --base     separate keys for Base mainnet (real funds: a few dollars of gas, no more)
import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { generatePrivateKey, privateKeyToAccount } from 'viem/accounts';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..'); // not from chain.js: that needs compiled contracts
const BASE = process.argv.includes('--base');
const file = join(ROOT, 'secrets', BASE ? 'base-keys.json' : 'testnet-keys.json');
if (existsSync(file)) {
  console.error(`${file} already exists; delete it yourself if you really want new keys.`);
  process.exit(1);
}
const out = BASE
  ? { warning: 'BASE MAINNET, REAL FUNDS. Keys in a plain file: fund the owner with a few dollars of gas, never more.', chains: [8453] }
  : { warning: 'TESTNET ONLY. Throwaway keys generated by app/src/keys.js. Never fund them on mainnet.', chains: [31337, 11155111] };
for (const role of ['owner', 'agent', 'guardian', 'attacker', 'landlord', 'school', 'utility']) {
  const privateKey = generatePrivateKey();
  out[role] = { address: privateKeyToAccount(privateKey).address, privateKey };
  console.log(`${role.padEnd(9)} ${out[role].address}`);
}
mkdirSync(join(ROOT, 'secrets'), { recursive: true });
writeFileSync(file, JSON.stringify(out, null, 2), { mode: 0o600 });
console.log(`saved ${file} (gitignored). Fund the owner address with ${BASE ? 'about 0.002 ETH on Base' : 'Sepolia ETH'} before deploying there.`);
