// Writes docs/evidence-sepolia.md: every Sepolia campaign in evidence/, newest first, each with its table
// (evidence-table.mjs) and a fresh audit from the chain and Blockscout (audit-chain.mjs --blockscout).
// Failed runs stay in, with what went wrong; nothing is dropped or re-labelled by hand.
// Usage: node scripts/evidence-doc.mjs
import { readdirSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const runs = readdirSync(join(ROOT, 'evidence')).filter((f) => /^sepolia-campaign-.*\.json$/.test(f)).sort();
const reference = runs.at(-1);

// What went wrong in each earlier run, in our harness (the vault refused every attack in all of them).
const NOTES = {
  'sepolia-campaign-20261014T120236.json': 'Two harness bugs. A8 was labelled `reverted:undefined`: the simulation before sending had hit an RPC node one block behind, said "ok", and no reason was recorded; the mined transaction reverts with `BadMandateSignature`. A9 ran out of gas: its forced buy had a 300,000 limit tuned on anvil, and creating storage costs far more on Sepolia (a swap: 2–2.4× its anvil gas), so it never reached the slippage check. The campaign file still called it a slippage refusal.',
  'sepolia-campaign-20261014T121554.json': 'The campaign file said 18/18 and our first audit agreed, because it replayed A9 without its gas limit. Blockscout showed "Out of gas": the forced buy hit the same 300,000 limit as in run 1. The audit now detects out-of-gas and replays with the transaction\'s own limit.',
  'sepolia-campaign-20261014T124422.json': 'Forced calls now had a 1,500,000 gas limit, but A9 was never sent. Our client library filled the transaction through `eth_fillTransaction`; the RPC node behind it simulated the call, saw the slippage revert and refused to fill it. Forced calls are now filled locally (nonce, fees, chain id, gas) and sent as they are.',
};

const node = process.execPath;
const run = (script, ...args) => {
  const p = spawnSync(node, [join(ROOT, 'scripts', script), ...args], { cwd: ROOT, encoding: 'utf8' });
  if (p.status !== 0 && !p.stdout.includes('as expected')) throw new Error(`${script} ${args.join(' ')}: ${p.stderr || p.stdout}`);
  return p.stdout.trim();
};

const out = [
  '# Sepolia evidence',
  '',
  `Generated by \`node scripts/evidence-doc.mjs\`. Every Sepolia campaign we ran is here, newest first. Each audit was re-run from the chain when this file was generated: it fetches every receipt, checks that the transaction went to the vault, flags out-of-gas, replays each refusal at its block with its own gas limit, and compares the result with Blockscout's independent decoding.`,
  '',
  `The vault refused every attack in every run. The first three runs still count as failures (17/18), because our harness sent or labelled one attack wrongly; each one is explained below. The fourth run is the reference.`,
  '',
];
for (const f of [...runs].reverse()) {
  const n = runs.indexOf(f) + 1;
  const audit = run('audit-chain.mjs', 'sepolia', join('evidence', f), '--blockscout');
  const verdict = audit.match(/= (\d+\/\d+) as expected/)[1];
  out.push(`## Run ${n}${f === reference ? ' (reference run)' : ' (kept as recorded)'}: ${verdict} after audit`, '');
  if (NOTES[f]) out.push(NOTES[f], '');
  out.push(run('evidence-table.mjs', 'sepolia', f), '');
  out.push(`Audit from the chain (\`node scripts/audit-chain.mjs sepolia evidence/${f} --blockscout\`):`, '');
  out.push('```', audit, '```', '');
}
writeFileSync(join(ROOT, 'docs', 'evidence-sepolia.md'), out.join('\n'));
console.log(`docs/evidence-sepolia.md: ${runs.length} runs, reference ${reference}`);
